function createTextElement(tag, className, text) {
  const el = document.createElement(tag);
  if (className) {
    el.className = className;
  }
  el.textContent = text;
  return el;
}

function createAiBadge() {
  const badge = createTextElement("span", "ai-badge", AI_BADGE_TEXT);
  badge.title = "Value generated by the AI model";
  return badge;
}

function createLoadBadge(loadType) {
  const label = LOAD_LABEL[loadType] ?? loadType;
  const pill = createTextElement("span", `load-badge ${LOAD_BADGE_CLASS[loadType] ?? ""}`, label);
  if (label !== loadType) {
    pill.title = `Load_Type: ${loadType}`;
    pill.setAttribute("aria-label", `${label} (Load_Type ${loadType})`);
  }
  return pill;
}

function createLegend(ariaLabel, items) {
  const legend = document.createElement("div");
  legend.className = "legend";
  legend.setAttribute("role", "group");
  legend.setAttribute("aria-label", ariaLabel);
  for (const item of items) {
    const entry = document.createElement("span");
    entry.className = "legend-item";
    entry.appendChild(item.marker);
    if (item.text) {
      entry.appendChild(createTextElement("span", "legend-text", item.text));
    }
    legend.appendChild(entry);
  }
  return legend;
}

function setHeadingText(heading, text) {
  for (const node of Array.from(heading.childNodes)) {
    if (node.nodeType === Node.TEXT_NODE) {
      heading.removeChild(node);
    }
  }
  heading.appendChild(document.createTextNode(text));
}

function explainStatTiles() {
  for (const [valueId, text] of Object.entries(STAT_TEXT)) {
    const valueEl = document.getElementById(valueId);
    const tile = valueEl?.closest(".stat-tile");
    if (!tile) {
      continue;
    }
    const labelEl = tile.querySelector(".stat-label");
    if (labelEl) {
      labelEl.textContent = text.label;
      if (text.ai) {
        labelEl.appendChild(createAiBadge());
      }
    }

    const descriptionId = `${valueId}-description`;
    const description = createTextElement("span", "metric-description", text.description);
    description.id = descriptionId;
    tile.appendChild(description);

    const describedBy = [descriptionId];
    if (text.status) {
      const status = createTextElement("span", "stat-status", "");
      status.id = text.status;
      tile.appendChild(status);
      describedBy.push(text.status);
    }
    tile.setAttribute("role", "group");
    tile.setAttribute("aria-label", text.label);
    valueEl.setAttribute("aria-describedby", describedBy.join(" "));
  }

  const statRow = document.querySelector(".stat-row");
  if (statRow) {
    const freshnessMarker = (tone) => createTextElement("span", `legend-dot legend-dot--${tone}`, "");
    const legend = createLegend("Data freshness levels", [
      { marker: createTextElement("span", "legend-title", "Data freshness:") },
      { marker: freshnessMarker("good"), text: "Fresh ≤ 1 min" },
      { marker: freshnessMarker("warning"), text: "Delayed 1–3 min" },
      { marker: freshnessMarker("critical"), text: "Stale > 3 min" },
    ]);
    legend.classList.add("stat-legend");
    statRow.insertAdjacentElement("afterend", legend);
  }
}

function explainPanels() {
  for (const [selector, text] of Object.entries(PANEL_TEXT)) {
    const panel = document.querySelector(selector);
    const heading = panel?.querySelector("h2");
    if (!heading) {
      continue;
    }
    setHeadingText(heading, text.title);
    const headingId = `${panel.className.split(" ")[0]}-title`;
    const descriptionId = `${panel.className.split(" ")[0]}-description`;
    heading.id = headingId;
    const description = createTextElement("p", "panel-description", text.description);
    description.id = descriptionId;
    heading.insertAdjacentElement("afterend", description);
    panel.setAttribute("role", "region");
    panel.setAttribute("aria-labelledby", headingId);
    panel.setAttribute("aria-describedby", descriptionId);
  }
}

function explainRecordsTable() {
  const panel = document.querySelector(".records-box");
  const headers = document.querySelectorAll(".records-table thead th");
  if (!panel || headers.length === 0) {
    return;
  }

  // Hidden definitions referenced by aria-describedby so screen readers get the full meaning.
  const definitions = document.createElement("div");
  definitions.hidden = true;
  for (const [term, help] of Object.entries(TERM_HELP)) {
    const def = createTextElement("span", "", help);
    def.id = `term-help-${term}`;
    definitions.appendChild(def);
  }
  panel.appendChild(definitions);

  headers.forEach((th, index) => {
    const term = HEADER_TERMS[index];
    if (!term) {
      return;
    }
    th.title = TERM_HELP[term];
    th.classList.add("term-help");
    th.setAttribute("aria-describedby", `term-help-${term}`);
    if (term === "Usage_kWh") {
      th.textContent = "";
      th.appendChild(document.createTextNode("Predicted"));
      th.appendChild(document.createElement("br"));
      th.appendChild(document.createTextNode("Usage_kWh"));
      th.appendChild(document.createElement("br"));
      th.appendChild(createAiBadge());
    }
  });

  const scroll = panel.querySelector(".records-scroll");
  const legend = createLegend("Table legend", [
    { marker: createAiBadge(), text: "Filled by the AI model" },
    { marker: createLoadBadge("Light_Load") },
    { marker: createLoadBadge("Medium_Load") },
    { marker: createLoadBadge("Maximum_Load"), text: "Load class, not a defect" },
  ]);
  const glossary = createTextElement(
    "p",
    "panel-description glossary",
    "Sensor inputs: kVarh = reactive energy · PF = power factor · CO2 = emissions (tCO2) · NSM = seconds since midnight. Hover a column header for details."
  );
  if (scroll) {
    scroll.insertAdjacentElement("beforebegin", legend);
    scroll.insertAdjacentElement("afterend", glossary);
  }
}

